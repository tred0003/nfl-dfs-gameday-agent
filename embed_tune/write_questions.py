def main() -> None:
    lines = SEEDS.read_text(encoding="utf-8", errors="replace").splitlines()
    with OUT.open("w", encoding="utf-8") as f:
        for i, (line, question, player, kind) in enumerate(Q, 1):
            seed = re.match(r"\[([^\]]+)\]", lines[line - 1]).group(1)
            f.write(json.dumps({"qid": f"q{i:03d}", "question": question, "player": player,
                                "kind": kind, "seed": seed}) + "\n")
    print(f"{len(Q)} questions -> {OUT}")


if __name__ == "__main__":
    main()
